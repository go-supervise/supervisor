//go:embed sysnum_amd64.txt
var sysnumAMD64 string

//go:embed sysnum_arm64.txt
var sysnumARM64 string

// archSpecific are listed names that one architecture does not have (the
// legacy epoll_wait of amd64; arm64 has only epoll_pwait).
var archSpecific = map[string]map[string]bool{
	"arm64": {"epoll_wait": true},
}

// SysNum is the table of Linux system-call numbers of an architecture, name to
// number: the SYS_* constants of golang.org/x/sys/unix, committed so that the
// dynamic half needs no package loading (`syscallsurface sysnum` regenerates
// it, and a test fails when it drifts).
func SysNum(arch string) map[string]int64 {
	var s string
	switch arch {
	case "amd64":
		s = sysnumAMD64
	case "arm64":
		s = sysnumARM64
	default:
		return nil
	}
	m := map[string]int64{}
	for _, l := range strings.Split(s, "\n") {
		if l = strings.TrimSpace(l); l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		f := strings.Fields(l)
		if len(f) != 2 {
			continue
		}
		if n, err := strconv.ParseInt(f[1], 10, 64); err == nil {
			m[f[0]] = n
		}
	}
	return m
}

// sysNames is SysNum reversed: number to name. Where two names share a number
// the alphabetically first one is the name, the same rule everywhere.
func sysNames(arch string) map[int64]string {
	tab := SysNum(arch)
	names := make([]string, 0, len(tab))
	for n := range tab {
		names = append(names, n)
	}
	sort.Strings(names)
	m := make(map[int64]string, len(tab))
	for _, n := range names {
		if _, dup := m[tab[n]]; !dup {
			m[tab[n]] = n
		}
	}
	return m
}

// GenerateSysNum renders the table for arch from the x/sys/unix of the module
// in dir.
func GenerateSysNum(dir, arch string) (string, error) {
	env := append(os.Environ(), "GOOS=linux", "GOARCH="+arch, "CGO_ENABLED=0")
	pkgs, err := packages.Load(&packages.Config{Mode: packages.LoadAllSyntax, Dir: dir, Env: env}, unixPath)
	if err != nil {
		return "", err
	}
	if len(pkgs) != 1 || pkgs[0].Types == nil {
		return "", fmt.Errorf("surface: cannot load %s for %s", unixPath, arch)
	}
	if len(pkgs[0].Errors) > 0 {
		return "", fmt.Errorf("surface: cannot load %s for %s: %v", unixPath, arch, pkgs[0].Errors[0])
	}
	scope := pkgs[0].Types.Scope()
	var lines []string
	for _, n := range scope.Names() {
		c, ok := scope.Lookup(n).(*types.Const)
		if !ok || !strings.HasPrefix(n, "SYS_") {
			continue
		}
		if v, ok := constant.Int64Val(c.Val()); ok {
			lines = append(lines, strings.ToLower(n[len("SYS_"):])+" "+strconv.FormatInt(v, 10))
		}
	}
	return "# Generated by `syscallsurface sysnum --arch " + arch + "`: do not edit.\n" + strings.Join(lines, "\n") + "\n", nil
}
